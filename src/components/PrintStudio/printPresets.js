export const interpolateCertificateBody = (templateText, vars = {}) => {
  if (!templateText) return "";
  return templateText.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const val = vars[key];
    return val !== undefined && val !== null && String(val).trim() !== "" ? String(val) : "—";
  });
};
